#!/usr/bin/env python3
"""The shell's type and icons for the watch: Adwaita Sans in the weights the
pages use and the Material glyphs of Symbols Nerd Font, cut down to what the
watch shows (a full font would not fit the app's budget).

  watch/tools/fonts.py          writes assets/default/fonts/ and lib/icons.js
                                for watch/app and watch/face

Needs fontTools (a venv will do). The icons are moved into the private use
area of the basic plane (U+E000…): the watch's text drawing is not trusted
with the supplementary planes where Nerd Font keeps them.
"""

import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

WATCH = Path(__file__).resolve().parents[1]
SANS = Path("/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf")
ICONS = Path("/usr/share/fonts/TTF/SymbolsNerdFont-Regular.ttf")
WEIGHTS = {"sans": 400, "medium": 560, "bold": 760}

# every icon a page or the face names; md- glyph names of Nerd Font
NAMES = """
robot robot_outline memory harddisk chip monitor monitor_dashboard music music_note play pause
skip_next skip_previous volume_high volume_medium volume_low volume_off volume_plus volume_minus mouse mouse_move_vertical
printer_3d printer_3d_nozzle download update email_outline bluetooth battery battery_charging
heart_pulse walk fire clock_outline timer_outline chart_donut thermometer chevron_right arrow_left
cellphone link_variant lan_disconnect check_circle alert_circle_outline sleep web gesture_tap
weather_sunny weather_night weather_partly_cloudy weather_night_partly_cloudy weather_cloudy
weather_fog weather_rainy weather_pouring weather_snowy weather_snowy_rainy weather_lightning
weather_lightning_rainy weather_windy weather_hail sun_clock headphones speaker cursor_move
lan lan_connect earth ethernet wifi lock lock_open_variant bell_off bell coffee record_rec server laptop
weather_sunset_up weather_sunset_down water_percent weather_windy_variant counter trophy bed
""".split()

# letters: Latin, German, the punctuation and signs the pages print
TEXT = (
    "".join(chr(c) for c in range(0x20, 0x7F))
    + "ÄÖÜäöüßéèêáàâóòôúùûíìîçñÉÈÁÀ"
    + "·•…–—‘’‚“”„«»°%‰±×÷−→←↑↓≈≤≥€£$§©®™¹²³½¼¾µ"
)


def sans(weight, target):
    import io

    # saved and read again: the subsetter trips over the instancer's lazy tables
    buffer = io.BytesIO()
    variable = TTFont(SANS)
    # every axis pinned (the weight to ours, the rest to their default): a static font
    axes = {axis.axisTag: axis.defaultValue for axis in variable["fvar"].axes}
    axes["wght"] = weight
    instancer.instantiateVariableFont(variable, axes).save(buffer)
    buffer.seek(0)
    font = TTFont(buffer)
    options = subset.Options()
    options.layout_features = ["kern", "liga", "tnum", "lnum"]
    options.name_IDs = ["*"]
    options.hinting = False
    worker = subset.Subsetter(options)
    worker.populate(text=TEXT)
    worker.subset(font)
    font.save(target)


def icons(target):
    font = TTFont(ICONS)
    order = set(font.getGlyphOrder())
    glyphs, mapping, missing = [], {}, []
    for name in NAMES:
        glyph = f"md-{name}"
        if glyph not in order:
            missing.append(name)
            continue
        mapping[name] = 0xE000 + len(glyphs)
        glyphs.append(glyph)
    if missing:
        print(f"no glyph for: {', '.join(missing)}", file=sys.stderr)
    options = subset.Options()
    options.notdef_outline = True
    options.hinting = False
    worker = subset.Subsetter(options)
    worker.populate(glyphs=glyphs)
    worker.subset(font)
    # the kept glyphs move to U+E000… in every cmap
    for table in font["cmap"].tables:
        if table.isUnicode():
            table.cmap = {mapping[g[3:]]: g for g in glyphs}
    font.save(target)
    return mapping


def main():
    for project in ("app", "face"):
        folder = WATCH / project / "assets" / "default" / "fonts"
        folder.mkdir(parents=True, exist_ok=True)
        for name, weight in WEIGHTS.items():
            sans(weight, folder / f"{name}.ttf")
        mapping = icons(folder / "icons.ttf")
    lines = ["// Generated by watch/tools/fonts.py: Material icon names → their character", "// in assets/default/fonts/icons.ttf.", "export const I = {"]
    lines += [f"  {name}: '\\u{code:04x}'," for name, code in mapping.items()]
    lines += ["}", ""]
    for project in ("app", "face"):
        (WATCH / project / "lib").mkdir(parents=True, exist_ok=True)
        (WATCH / project / "lib" / "icons.js").write_text("\n".join(lines))
    sizes = {p.name: p.stat().st_size for p in (WATCH / "app" / "assets" / "default" / "fonts").iterdir()}
    print(json.dumps(sizes))


if __name__ == "__main__":
    main()
